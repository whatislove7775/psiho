"""Телефоны помощи по странам — для Тиши. Зеркало apps/web/src/lib/i18n/countries.ts (там же источники).

Только общеизвестные национальные службы, проверенные по сайтам операторов (сентябрь 2026).
Для остальных стран — экстренный номер и каталог findahelpline.com (ThroughLine).
"""

# code → (экстренный номер, [(название, телефон, пояснение)])
CRISIS: dict[str, tuple[str, list[tuple[str, str, str]]]] = {
    "RU": ("112", [
        ("кризисная линия психологической помощи для взрослых", "8-800-333-44-34", "бесплатно, круглосуточно"),
        ("детский телефон доверия для детей, подростков и их родителей", "8-800-2000-122", "бесплатно, анонимно"),
        ("экстренная психологическая помощь в Москве", "051 (с мобильного +7 495 051)", ""),
    ]),
    "BY": ("112", [("экстренная психологическая помощь", "133", "бесплатно, круглосуточно")]),
    "KZ": ("112", [("единый контакт-центр «111», в том числе психологическая помощь", "111", "круглосуточно")]),
    "UZ": ("112", []),
    "KG": ("103", []),
    "AM": ("911", []),
    "AZ": ("112", []),
    "GE": ("112", []),
    "MD": ("112", []),
    "UA": ("112", [("Lifeline Ukraine, линия предотвращения суицидов", "7333", "бесплатно, круглосуточно")]),
    "US": ("911", [("988 Suicide & Crisis Lifeline", "988", "звонок или SMS, круглосуточно")]),
    "CA": ("911", [("9-8-8 Suicide Crisis Helpline", "988", "звонок или SMS, круглосуточно")]),
    "GB": ("999", [("Samaritans", "116 123", "бесплатно, круглосуточно")]),
    "IE": ("112", [("Samaritans", "116 123", "бесплатно, круглосуточно")]),
    "DE": ("112", [("TelefonSeelsorge", "0800 111 0 111", "бесплатно, круглосуточно")]),
}
DIRECTORY = "https://findahelpline.com"


def safety_block(country: str | None) -> str:
    """Строки протокола безопасности для системного промпта Тиши."""
    code = (country or "RU").upper()
    emergency, lines = CRISIS.get(code, ("112", []))
    out = [f"  • {emergency} — номер экстренных служб в стране пользователя (бесплатно, с любого телефона);"]
    for name, phone, note in lines:
        out.append(f"  • {phone} — {name}" + (f" ({note})" if note else "") + ";")
    if code not in CRISIS or not lines:
        out.append(f"  • {DIRECTORY} — проверенный каталог телефонов доверия по странам;")
        if code not in CRISIS:
            out.append("  • если человек назвал другую страну — посоветуй местный номер экстренных служб "
                       "(112 в Европе, 911 в США и Канаде, 999 в Великобритании) и каталог выше.")
    return "\n".join(out)
