_PLAIN: dict[str, str] = {}
_PATTERNS: list[tuple[re.Pattern, str]] = []
for _ru, _en in EN.items():
    if re.search(r"\{x\d\}", _ru):
        parts = re.split(r"(\{x\d\})", _ru)
        rx = "".join(f"(?P<{p[1:-1]}>.+?)" if re.fullmatch(r"\{x\d\}", p) else re.escape(p) for p in parts)
        _PATTERNS.append((re.compile(f"^{rx}$", re.S), _en))
    else:
        _PLAIN[_ru] = _en


def translate(text: str, lang: str) -> str:
    """Русский текст → язык lang (пока только en). Неизвестное возвращается как есть."""
    if lang == "ru" or not text or not isinstance(text, str):
        return text
    hit = _PLAIN.get(text)
    if hit is not None:
        return hit
    for rx, template in _PATTERNS:
        m = rx.match(text)
        if m:
            return template.format(**m.groupdict())
    return text


def tr(text: str) -> str:
    """Перевод на активный язык запроса (для текстов в успешных ответах и SSE)."""
    return translate(text, (translation.get_language() or "ru").split("-")[0])
