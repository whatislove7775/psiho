_EMAIL = re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")
_PHONE = re.compile(r"(?<!\d)(?:\+?\d[\s\-()]*){10,14}(?!\d)")

HISTORY_LIMIT = 40
MAX_TOKENS = 4096


def scrub(text: str) -> str:
    """Убирает email и телефоны перед отправкой провайдеру."""
    return _PHONE.sub("[скрыто]", _EMAIL.sub("[скрыто]", text))


def build_history(pairs: list[tuple[str, str]]) -> list[dict]:
    """pairs: [(sender_role, text)] по времени → messages для Claude API.

    Первое сообщение должно быть от пользователя; подряд идущие реплики одной
    стороны объединяются.
    """
    out: list[dict] = []
    for role, text in pairs[-HISTORY_LIMIT:]:
        api_role = "assistant" if role == "ai" else "user"
        if not text:
            continue
        if api_role == "user":
            text = scrub(text)
        if not out and api_role == "assistant":
            continue
        if out and out[-1]["role"] == api_role:
            out[-1]["content"] += "\n\n" + text
        else:
            out.append({"role": api_role, "content": text})
    return out


def enabled() -> bool:
    provider = get_provider()
    return bool(provider and provider.configured())


async def stream_reply(history: list[dict]) -> AsyncIterator[str]:
    """Стримит ответ выбранного провайдера по кусочкам текста. Бросает AIRefusal при отказе."""
    provider = get_provider()
    if provider is None or not provider.configured():
        raise RuntimeError("AI provider is not configured")
    async for text in provider.stream(SYSTEM_PROMPT, history, MAX_TOKENS):
        yield text
